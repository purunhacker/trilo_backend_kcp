-- 1. 기존 활성 버전 비활성화 (한 약관당 활성 버전은 하나)
UPDATE term_versions
SET is_active = false,
    updated_at = NOW()
WHERE is_active = true
  AND term_id = (SELECT id FROM terms WHERE code = 'health_data');

