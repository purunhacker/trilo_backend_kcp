-- ================================================================
-- V15: health_data 약관 본문을 HTML로 재포맷
--
-- 약관 본문은 클라이언트가 HTML로 렌더한다(웹 Terms.html 은 innerHTML,
-- 앱/프로필 모달은 dangerouslySetInnerHTML). V14 는 평문 + 줄바꿈으로 넣어서
-- 줄바꿈이 전부 무시되고 한 덩어리로 보였다.
--
-- ⚠️ 문구(법적 내용)는 한 글자도 바꾸지 않고 마크업만 입힌다. 그래서 새 버전을
--    만들지 않고 활성 버전(2026-09-04)의 content 를 그대로 갱신한다 —
--    새 버전을 내면 기존 동의가 전부 무효가 되어 재동의를 다시 받아야 하는데,
--    표시 형식 변경으로 재동의를 요구하는 것은 과하다.
--
-- 제목은 클라이언트가 title 필드로 따로 노출하므로 본문에서 제목 줄은 뺀다.
--
-- 이미 어드민이 본문을 직접 손봤다면(HTML 태그가 들어 있다면) 건드리지 않는다.
-- ================================================================

UPDATE term_versions
SET content = '<p>Trilo는 사용자가 기록한 경로에 심박수 변화를 함께 보여주기 위해 Apple 건강(HealthKit) 앱의 심박수 정보를 연동합니다.</p>
<ol>
  <li><strong>수집·이용 항목:</strong> 심박수(bpm)와 그 측정 시각</li>
  <li><strong>이용 목적:</strong> 사용자가 기록한 경로(여행) 구간별 심박수 변화와 요약값(평균·최고·최저)을 사용자 본인에게 표시</li>
  <li>
    <strong>처리 방식</strong>
    <ul>
      <li>연동에 동의하면 앱이 읽어온 심박수가 Trilo 서버에 저장됩니다.</li>
      <li>측정된 값을 그대로 저장하지 않고, 10초 단위로 요약(구간 평균)한 값과 기록 전체의 평균·최고·최저 심박수만 저장합니다.</li>
      <li>저장된 심박수는 본인만 조회할 수 있습니다. 여행을 공개로 설정하더라도 다른 사용자에게는 공개되지 않습니다.</li>
      <li>제3자에게 제공하거나 판매하지 않으며, 광고·마케팅 목적으로 이용하지 않습니다.</li>
    </ul>
  </li>
  <li><strong>보유·이용 기간:</strong> 해당 여행 기록이 삭제되거나 회원에서 탈퇴하면 함께 파기됩니다. 여행 기록은 그대로 두고 심박수만 따로 삭제할 수도 있습니다.</li>
  <li><strong>동의 거부 권리 및 불이익:</strong> 본 동의는 선택 사항이며, 동의하지 않아도 경로 기록 등 Trilo의 기본 서비스는 정상 이용할 수 있습니다. 동의하지 않으면 심박수는 서버로 전송되지 않습니다.</li>
  <li><strong>동의 철회:</strong> 기기의 설정 &gt; 개인정보 보호 및 보안 &gt; 건강, 또는 Trilo 앱 설정에서 언제든 연동을 해제할 수 있습니다. 철회하면 이후로는 심박수가 수집·전송되지 않으며, 이미 저장된 심박수는 여행별로 삭제할 수 있습니다.</li>
</ol>',
    updated_at = NOW()
WHERE version = '2026-09-04'
  AND term_id = (SELECT id FROM terms WHERE code = 'health_data')
  AND content NOT LIKE '%<%';
